-- 0001_baseline_schema.sql
-- PURPOSE   Create the tables the application expects on a BRAND-NEW database (new client instance).
-- EXISTING DATABASES  Safe to run: every statement is CREATE ... IF NOT EXISTS / guarded, so existing tables, columns and data are
--           never altered or dropped. It only fills in what is missing (and repairs auto-numbering of categories/menu_items ids,
--           which the old app used to do at every start).
-- NOTE      The column list was INFERRED from the application's SQL (the original schema was not in the project). On a live
--           database run migrations/diagnostics/03_schema_inventory.sql first and compare. NOT EXECUTED by the author.
-- ROLLBACK  None needed for existing databases (nothing is changed). On a new empty database, drop the tables.

BEGIN;

CREATE TABLE IF NOT EXISTS public.settings (
    id                 INTEGER PRIMARY KEY,
    business_name      TEXT NOT NULL DEFAULT '',
    address            TEXT NOT NULL DEFAULT '',
    phone              TEXT NOT NULL DEFAULT '',
    gst_number         TEXT NOT NULL DEFAULT '',
    food_license       TEXT NOT NULL DEFAULT '',
    printer_name       TEXT NOT NULL DEFAULT '58mm Mini Thermal Printer',
    paper_size         TEXT NOT NULL DEFAULT '58mm',
    auto_print         BOOLEAN NOT NULL DEFAULT FALSE,
    default_order_type TEXT NOT NULL DEFAULT 'Pickup',
    tax_percent        NUMERIC(6,2) NOT NULL DEFAULT 0,
    delivery_fee       NUMERIC(10,2) NOT NULL DEFAULT 0,
    printer_mode       TEXT NOT NULL DEFAULT 'browser',
    printer_target     TEXT NOT NULL DEFAULT '',
    printer_baudrate   INTEGER NOT NULL DEFAULT 9600
);

CREATE TABLE IF NOT EXISTS public.categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT NOT NULL UNIQUE,
    icon       TEXT NOT NULL DEFAULT '',
    sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.menu_items (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      TEXT NOT NULL,
    category  TEXT NOT NULL DEFAULT 'Other',
    price     NUMERIC(10,2) NOT NULL CHECK (price > 0),
    available BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS public.orders (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number         INTEGER NOT NULL,
    customer_name        TEXT NOT NULL DEFAULT '',
    phone                TEXT NOT NULL DEFAULT '',
    address              TEXT NOT NULL DEFAULT '',
    table_number         TEXT NOT NULL DEFAULT '',
    order_type           TEXT NOT NULL DEFAULT 'Pickup',
    subtotal             NUMERIC(12,2) NOT NULL DEFAULT 0,
    delivery_fee         NUMERIC(10,2) NOT NULL DEFAULT 0,
    tax                  NUMERIC(12,2) NOT NULL DEFAULT 0,
    total                NUMERIC(12,2) NOT NULL DEFAULT 0,
    special_instructions TEXT NOT NULL DEFAULT '',
    payment_method       TEXT NOT NULL DEFAULT 'Cash',
    payment_status       TEXT NOT NULL DEFAULT 'Pending',
    status               TEXT NOT NULL DEFAULT 'New',
    created_at           TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')   -- naive UTC, as the app stores it
);

CREATE TABLE IF NOT EXISTS public.order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    menu_item_id BIGINT,
    item_name    TEXT NOT NULL,
    quantity     INTEGER NOT NULL CHECK (quantity >= 1),
    unit_price   NUMERIC(10,2) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_order_items_order_id ON public.order_items(order_id);
CREATE INDEX IF NOT EXISTS idx_orders_created_at    ON public.orders(created_at);

CREATE TABLE IF NOT EXISTS public.inventory_purchases (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name     TEXT NOT NULL,
    category      TEXT NOT NULL DEFAULT 'Raw Material',
    quantity      NUMERIC(14,3) NOT NULL DEFAULT 1,
    unit          TEXT NOT NULL DEFAULT 'kg',
    unit_price    NUMERIC(14,2) NOT NULL DEFAULT 0,
    total_cost    NUMERIC(14,2) NOT NULL DEFAULT 0,
    purchase_date DATE NOT NULL,
    notes         TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS public.users (
    id                   SERIAL PRIMARY KEY,
    username             TEXT NOT NULL UNIQUE,
    name                 TEXT NOT NULL DEFAULT '',
    password_hash        TEXT NOT NULL,
    role                 TEXT NOT NULL DEFAULT 'staff',
    active               BOOLEAN NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
    created_at           TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS public.sessions (
    token_hash TEXT PRIMARY KEY,          -- SHA-256 of the cookie token; the token itself is never stored
    user_id    INTEGER NOT NULL,
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sessions_user_id    ON public.sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_expires_at ON public.sessions(expires_at);

-- Columns older versions added at startup (no-ops when already present):
ALTER TABLE public.settings ADD COLUMN IF NOT EXISTS food_license TEXT NOT NULL DEFAULT '';
ALTER TABLE public.orders   ADD COLUMN IF NOT EXISTS table_number TEXT NOT NULL DEFAULT '';
ALTER TABLE public.users    ADD COLUMN IF NOT EXISTS must_change_password BOOLEAN NOT NULL DEFAULT FALSE;

-- Repair: categories/menu_items ids must generate themselves (the old app fixed this at every start).
DO $$
DECLARE t text; col record; seq text; mx bigint;
BEGIN
  FOREACH t IN ARRAY ARRAY['categories','menu_items'] LOOP
    SELECT column_default, is_identity INTO col FROM information_schema.columns
     WHERE table_schema='public' AND table_name=t AND column_name='id';
    IF FOUND AND col.is_identity <> 'YES' AND (col.column_default IS NULL OR upper(col.column_default) LIKE 'NULL%') THEN
      IF col.column_default IS NOT NULL THEN EXECUTE format('ALTER TABLE public.%I ALTER COLUMN id DROP DEFAULT', t); END IF;
      EXECUTE format('ALTER TABLE public.%I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', t);
      seq := pg_get_serial_sequence(format('public.%I', t), 'id');
      EXECUTE format('SELECT COALESCE(MAX(id),0) FROM public.%I', t) INTO mx;
      IF seq IS NOT NULL THEN
        IF mx > 0 THEN PERFORM setval(seq::regclass, mx, TRUE); ELSE PERFORM setval(seq::regclass, 1, FALSE); END IF;
      END IF;
      RAISE NOTICE 'Repaired automatic ids for public.%', t;
    END IF;
  END LOOP;
END $$;

COMMIT;
